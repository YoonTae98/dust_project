# 각 교차점 사이를 OSRM 실제 도로망으로 정밀 스냅
def get_route_coords(p1, p2):
    url = f"http://router.project-osrm.org/route/v1/driving/{p1[1]},{p1[0]};{p2[1]},{p2[0]}?overview=full&geometries=geojson"
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        with urllib.request.urlopen(req, timeout=6) as res:
            d = json.loads(res.read().decode('utf-8'))
            if d.get('routes'):
                coords = d['routes'][0]['geometry']['coordinates']
                return [[round(c[1], 6), round(c[0], 6)] for c in coords]
    except Exception:
        pass
    return [[round(p1[0], 6), round(p1[1], 6)], [round(p2[0], 6), round(p2[1], 6)]]

def build_multiline_segments(segment_list):
    lines = []
    for p1, p2 in segment_list:
        pts = get_route_coords(p1, p2)
        lines.append(pts)
    return lines

